def sr(run, size=None, bold=None, font=None, color=None):
    run.font.name = font or SONG
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font or SONG)
    if size: run.font.size = Pt(size)
    if bold is not None: run.font.bold = bold
    if color: run.font.color.rgb = color
    return run


def body(text, size=12, indent=True, align=None, sa=0, sb=0, color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    if indent: pf.first_line_indent = Pt(size * 2)
    pf.space_before, pf.space_after = Pt(sb), Pt(sa)
    if align is not None: p.alignment = align
    sr(p.add_run(text), size=size, color=color)
    return p


def h(text, level=1):
    cfg = {1: (16, 14, 8), 2: (13.5, 12, 5), 3: (12, 8, 3)}
    size, sb, sa = cfg[level]
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_before = Pt(sb)
    p.paragraph_format.space_after = Pt(sa)
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.line_spacing = 1.5
    sr(p.add_run(text), size=size, bold=True, font=HEI)
    return p


def cap(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(9)
