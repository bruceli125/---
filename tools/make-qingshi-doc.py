def fig(name, caption, width=15.2):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(os.path.join(FIG, name), width=Cm(width))
    cap(caption)


def table(headers, rows, widths, size=10, center_cols=(0,)):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    tp = t._tbl.tblPr
    w = tp.find(qn("w:tblW"))
    if w is None:
        w = OxmlElement("w:tblW"); tp.append(w)
    w.set(qn("w:type"), "dxa"); w.set(qn("w:w"), str(int(sum(widths) * 566.929)))
    for i, wd in enumerate(widths):
        t.columns[i].width = Cm(wd)
    for i, hd in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ""
        p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(2); p.paragraph_format.line_spacing = 1.15
        sr(p.add_run(hd), size=size, bold=True, font=HEI)
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), "F2F4F8")
        c._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(2); p.paragraph_format.line_spacing = 1.15
            if i in center_cols: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            sr(p.add_run(str(v)), size=size)
    for r in t.rows:
        for i, wd in enumerate(widths):
            r.cells[i].width = Cm(wd)
    return t


